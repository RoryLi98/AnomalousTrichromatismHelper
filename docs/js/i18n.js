let current = 'zh';

export function setLang(lang) { current = STRINGS[lang] ? lang : 'zh'; }
export function getLang() { return current; }

export function t(key, vars) {
  let s = (STRINGS[current] && STRINGS[current][key]) ?? STRINGS.en[key] ?? key;
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace('{' + k + '}', v);
  return s;
}

/** Apply translations to all [data-i18n] (textContent) and [data-i18n-aria] elements. */
export function applyI18n(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-aria]').forEach((el) => {
    const v = t(el.dataset.i18nAria);
    el.setAttribute('aria-label', v);
    el.setAttribute('title', v);
  });
  document.documentElement.lang = current === 'zh' ? 'zh-CN' : 'en';
  document.title = t('app.title');
}

/** Guess the initial language from the browser. */
export function detectLang() {
  const l = (navigator.languages && navigator.languages[0]) || navigator.language || 'zh';
  return /^zh/i.test(l) ? 'zh' : 'en';
}
